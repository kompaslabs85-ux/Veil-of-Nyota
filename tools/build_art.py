#!/usr/bin/env python3
"""Warden Wars v2 art pipeline. Sources: /workspace/game-art/v2 (painted, 2-3x+).
Cuts out with rembg (isnet-general-use), trims, exports 1x/2x/3x webp (downscale only).
Writes js/manifest.js with logical sizes + max safe logical height (src_h/3)."""
import os, json, io, sys
from PIL import Image, ImageEnhance
import numpy as np
from rembg import remove, new_session
SRC='/workspace/game-art/v2'; OUT=os.path.join(os.path.dirname(__file__),'..','assets','v2')
os.makedirs(OUT,exist_ok=True)
S=[new_session('isnet-general-use'),new_session('u2net')]
from scipy import ndimage
man={}; report=[]
def cut(im):
    """Run two matting models; keep the one with the cleanest matte, then binarise residue."""
    best=None
    for ses in S:
        a=np.array(remove(im.convert('RGB'),session=ses)); al=a[...,3]
        op=(al>160).mean(); semi=((al>16)&(al<160)).mean()
        if op<0.04: continue
        sc=semi/op
        if best is None or sc<best[0]: best=(sc,a)
    a=best[1]; al=a[...,3].astype(float)
    al[al<90]=0
    lab,n=ndimage.label(al>0)
    if n>1:
        sz=ndimage.sum(np.ones_like(al),lab,range(1,n+1)); keep=[i+1 for i,v in enumerate(sz) if v>=0.03*sz.max()]
        al[~np.isin(lab,keep)]=0
    a[...,3]=al.astype(np.uint8)
    ys,xs=np.where(al>0)
    return Image.fromarray(a).crop((xs.min(),ys.min(),xs.max()+1,ys.max()+1))
def export(name,im,H,kind):
    w,h=im.size
    maxH=h/3.0
    if H>maxH: report.append(f'WARN {name}: wanted {H} > max {maxH:.1f}; clamped'); H=int(maxH)
    lw=w*H/h
    for n in (1,2,3):
        th=round(H*n); tw=max(1,round(lw*n))
        assert th<=h, 'upscale!'
        im.resize((tw,th),Image.LANCZOS).save(f'{OUT}/{name}@{n}x.webp',quality=90,method=6)
    # 4x tier for DPR3 phones wider than 360 css px (device px per logical px up to ~3.3): capped at source size, never upscaled
    th4=min(round(H*4),h); tw4=max(1,round(w*th4/h)); im.resize((tw4,th4),Image.LANCZOS).save(f'{OUT}/{name}@4x.webp',quality=90,method=6)
    man[name]={'w':round(lw,1),'h':H,'src':[w,h],'px':[round(H),round(H*2),round(H*3),th4],'kind':kind}
    report.append(f'{name}: src {w}x{h} -> logical {lw:.0f}x{H} (3x={round(H*3)}px, downscale {h/(H*3):.2f}x)')
def load(p): return Image.open(os.path.join(SRC,p))
# enemies
E={'husk':('enemies/enemy-01-shard-maiden.jpg',45),'ling':('enemies/enemy-02-scarlet-courier.jpg',45),
   'shard':('enemies/enemy-03-crimson-vowknight.jpg',54),'harpy':('gen/harpy-clean.jpg',54),
   'moth':('enemies/enemy-05-moth-enchantress-flyer.jpg',45),'siren':('enemies/enemy-06-siren-of-the-lyre.jpg',54)}
for k,(p,H) in E.items(): export('e_'+k,cut(load(p)),H,'enemy')
for i in (1,2,3): export(f'e_herald{i}',cut(load(f'enemies/boss-herald-stage{i}.jpg')),102,'boss')
# heroes (field 64, splash 300)
HER={'thandeka':['concepts/evo-thandeka-E1-oathkeeper.jpg','concepts/evo-thandeka-E2-glacier-sworn.jpg','concepts/evo-thandeka-E3-living-mountain.jpg'],
     'jabari':['concepts/02-ashgate-jabari-M.jpg','gen/jabari-E2.jpg','gen/jabari-E3.jpg']}
base={'thandeka':'concepts/01-rimehold-thandeka-F.jpg','jabari':'concepts/02-ashgate-jabari-M.jpg'}
for h,lst in HER.items():
    for i,p in enumerate([base[h]]+lst):
        c=cut(load(p)); export(f'h_{h}{i}',c,64,'hero')
        if i in (0,3): export(f'hs_{h}{i}',c,300,'splash')
        if i==0:
            w,hh=c.size; s=int(w*0.62); x=(w-s)//2
            export(f'pt_{h}',c.crop((x,0,x+s,s)),120,'portrait')
# towers
TK={'stone':['monolith','drum','spire','bastion','skyhook'],'forge':['cannon','slag','lance','bell','kiln']}
SH={'stone':'rimehold','forge':'ashgate'}
for f,keys in TK.items():
    b=load(f'towers/towers-{SH[f]}-base.jpg'); br=load(f'towers/towers-{SH[f]}-branches-A-top-B-bottom.jpg')
    for i,k in enumerate(keys):
        export(f't_{k}_1',cut(b.crop((i*256,0,i*256+256,720))),64,'tower')
        export(f't_{k}_A',cut(br.crop((i*256,0,i*256+256,360))),74,'tower')
        export(f't_{k}_B',cut(br.crop((i*256,360,i*256+256,720))),74,'tower')
pg=load('towers/towers-rimehold-icefang-progression-L1-L4-L7-L10.png').convert('RGB')
for i,l in enumerate([1,4,7,10]):
    export(f't_spire_p{l}',cut(pg.crop((i*320,0,i*320+320,720))),[60,66,72,78][i],'tower')
# textures: 3x tile is source 1024; 1 src px = 1 device px
for t,d in [('snow',0.70),('iceroad',0.80),('soot',1.15),('cobble',0.95)]:
    im=Image.open(f'{SRC}/gen/tex-{t}.jpg').convert('RGB'); im=ImageEnhance.Brightness(im).enhance(d)
    for n in (1,2,3):
        s=round(1024*n/3); im.resize((s,s),Image.LANCZOS).save(f'{OUT}/x_{t}@{n}x.webp',quality=88)
    man['x_'+t]={'w':1024/3,'h':1024/3,'kind':'texture'}
open(os.path.join(os.path.dirname(__file__),'..','js','manifest.js'),'w').write('// generated by tools/build_art.py\nconst ART_MANIFEST='+json.dumps(man)+';\n')
open(os.path.join(OUT,'BUILD-REPORT.txt'),'w').write('\n'.join(report)); print('\n'.join(report))
